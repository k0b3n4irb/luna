#!/usr/bin/env python3
"""Write ORACLE.json: which oracles luna's gates validated for one commit.

The file is produced from the REAL results of the gates, never by hand:
CI runs this script after the gates (the artifact `oracle-json` of the
`tom-harte` workflow and of the `snes-test-roms` / `docs` jobs of `ci.yml`),
and a developer runs it on local logs to get the same file for a build.

    tools/oracle-json.py --tom-harte-65816 th816.log --tom-harte-spc700 thspc.log \
        --snes-test-roms roms.log --doc-drift drift.log -o ORACLE.json

Every input is optional; a gate with no log and no outcome is `skipped`.
`--outcome NAME=success|failure|cancelled|skipped` passes a CI step outcome
(`steps.<id>.outcome`); the log is still read, and a log that contradicts a
`success` outcome turns the gate into `fail`. NAME is one of: tom-harte-65816,
tom-harte-spc700, snes-test-roms, doc-drift.

The Tom Harte counts are parsed from the report the harness already prints
(`cargo test ... --nocapture`, stderr) -- the harness is not modified. The
numbers that define the baseline (the contested states, the dataset size) are
read from the harness source, so they cannot drift from it.

Schema 1. `not_proven` is a fixed list kept in this file: what no gate can
claim, whatever its colour. See book/src/method/testing.md ("ORACLE.json").
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = 1

HARNESS_65816 = "crates/luna-cpu-65c816/tests/tom_harte.rs"
HARNESS_SPC700 = "crates/luna-cpu-spc700/tests/tom_harte.rs"

# The code a Tom Harte run exercises: a commit that touches none of it
# inherits the last run on the same code (the tom-harte workflow's paths,
# plus the APU crate that runs the production SPC700).
CORE_PATHS = [
    "crates/luna-cpu-65c816",
    "crates/luna-cpu-spc700",
    "crates/luna-apu",
    "crates/luna-bus/src/testing.rs",
    "crates/luna-bus/src/bus.rs",
    "crates/luna-bus/src/types.rs",
]

GATE_NAMES = ["tom-harte-65816", "tom-harte-spc700", "snes-test-roms", "doc-drift"]
GATE_WHERE = {
    "tom-harte-65816": "tom-harte.yml / tom-harte",
    "tom-harte-spc700": "tom-harte.yml / tom-harte",
    "snes-test-roms": "ci.yml / snes-test-roms",
    "doc-drift": "ci.yml / docs",
}

# Fixed: what no gate proves, whatever its colour. Edit here, nowhere else.
NOT_PROVEN = [
    "Tom Harte vectors are generated by a software model of the CPUs, not "
    "captured on a console: a pass proves agreement with that model.",
    "PNG / hash goldens of the test ROMs are luna's own output or emulator "
    "captures of unverified provenance: they catch regressions, they do not "
    "prove the picture is what a console draws.",
    "The contested (dp,X) states (emulation mode, D.l != 0, pointer at the end "
    "of a page; see `contested` in the 65C816 gate) follow ares and Mesen2, "
    "against the dataset.",
    "Coprocessor behaviour (SA-1, Super FX, DSP-1, S-DD1) and the absolute "
    "audio level are not calibrated on a console.",
]


# ---------------------------------------------------------------- parsing

def _int(rx: str, text: str) -> int | None:
    m = re.search(rx, text, re.M)
    return int(m.group(1)) if m else None


def parse_tom_harte_blocks(log: str) -> list[dict]:
    """One dict per `Tom Harte ... results` report block of the log."""
    blocks = []
    parts = re.split(r"^\s*Tom Harte (?:65C816|SPC700) — ", log, flags=re.M)[1:]
    for part in parts:
        head, _, body = part.partition("\n")
        # stop at the next report so that counts never leak across blocks
        sect = {"name": head.replace("results", "").strip()}
        sect["files"] = _int(r"Files processed:\s*(\d+)", body)
        sect["pass"] = _int(r"^\s*Pass:\s*(\d+)", body)
        sect["fail"] = _int(r"^\s*Fail:\s*(\d+)", body)
        sect["panicked"] = _int(r"^\s*Panicked:\s*(\d+)", body)
        cyc = re.search(
            r"(?:Cycle-count backstop|Cycle-trace check)[^\n]*\n\s*Match:\s*(\d+)\n\s*Mismatch:\s*(\d+)",
            body,
        )
        sect["cycle_match"], sect["cycle_mismatch"] = (
            (int(cyc.group(1)), int(cyc.group(2))) if cyc else (None, None)
        )
        tr = re.search(r"Per-cycle bus-trace oracle[^\n]*\n\s*Match:\s*(\d+)\n\s*Diverge:\s*(\d+)", body)
        sect["trace_match"], sect["trace_diverge"] = (
            (int(tr.group(1)), int(tr.group(2))) if tr else (None, None)
        )
        blocks.append(sect)
    return blocks


def harness_const(path: str, name: str) -> int | None:
    src = (ROOT / path).read_text()
    m = re.search(rf"const {name}: usize = ([\d_]+);", src)
    return int(m.group(1).replace("_", "")) if m else None


def contested_states() -> tuple[int, int]:
    """(states, trace divergences) the 65C816 harness accepts, from its source."""
    src = (ROOT / HARNESS_65816).read_text()
    m = re.search(r"const CONTESTED_STATE:[^=]*=\s*\[(.*?)\];", src, re.S)
    rows = re.findall(r'\(\s*"[0-9a-f]{2}\.[en]"\s*,\s*(\d+)\s*,\s*(\d+)\s*\)', m.group(1)) if m else []
    return sum(int(a) for a, _ in rows), sum(int(b) for _, b in rows)


def cargo_verdict(log: str) -> str | None:
    """'ok' / 'FAILED' from the last `test result:` line, None when absent."""
    last = re.findall(r"^test result: (ok|FAILED)\.", log, re.M)
    if not last:
        return None
    return "FAILED" if "FAILED" in last else "ok"


def cargo_counts(log: str) -> dict:
    tot = {"passed": 0, "failed": 0, "ignored": 0}
    for p, f, i in re.findall(r"test result: \w+\. (\d+) passed; (\d+) failed; (\d+) ignored", log):
        tot["passed"] += int(p)
        tot["failed"] += int(f)
        tot["ignored"] += int(i)
    return tot


# ------------------------------------------------------------------ gates

def outcome_result(outcome: str | None) -> str | None:
    return {None: None, "success": "pass", "skipped": "skipped"}.get(outcome, "fail")


def tom_harte_65816(log: str) -> tuple[str, dict, str | None]:
    blocks = parse_tom_harte_blocks(log)
    counts: dict = {}
    if len(blocks) != 1 or blocks[0]["pass"] is None:
        return "fail", counts, "no complete 65C816 report in the log"
    b = blocks[0]
    contested, contested_trace = contested_states()
    total = b["pass"] + b["fail"] + b["panicked"]
    full = harness_const(HARNESS_65816, "EXPECTED_FILES") * harness_const(HARNESS_65816, "CASES_PER_FILE")
    counts = {
        "states_passed": b["pass"],
        "states_total": total,
        "states_failed_reported": b["fail"],
        "panicked": b["panicked"],
        "contested": contested,
        "not_run": max(full - total, 0),
        "cycle_count_match": b["cycle_match"],
        "cycle_count_mismatch": b["cycle_mismatch"],
        "bus_trace_match": b["trace_match"],
        "bus_trace_diverge": b["trace_diverge"],
        "contested_trace_diverge": contested_trace,
    }
    note = None
    ok = (
        cargo_verdict(log) == "ok"
        and b["panicked"] == 0
        and b["fail"] == contested          # the gate's baseline, exactly
        and b["cycle_mismatch"] == 0
    )
    if "Sampling first" in log:
        return "skipped", counts, "sampled run (not the full dataset): not a gate"
    if not ok:
        note = "gate failed or the report departs from the baseline"
    return ("pass" if ok else "fail"), counts, note


def tom_harte_spc700(log: str) -> tuple[str, dict, str | None]:
    blocks = parse_tom_harte_blocks(log)
    if len(blocks) != 2 or any(b["pass"] is None for b in blocks):
        return "fail", {}, "expected the two core reports (production, atomic) in the log"
    counts = {}
    ok = cargo_verdict(log) == "ok"
    for b in blocks:
        key = "production" if b["name"].startswith("production") or "step_cycle" in b["name"] else "atomic"
        total = b["pass"] + b["fail"] + b["panicked"]
        counts[key] = {
            "states_passed": b["pass"],
            "states_total": total,
            "panicked": b["panicked"],
            "cycle_trace_match": b["cycle_match"],
            "cycle_trace_mismatch": b["cycle_mismatch"],
        }
        ok = ok and b["fail"] == 0 and b["panicked"] == 0 and b["cycle_mismatch"] == 0
    full = harness_const(HARNESS_SPC700, "EXPECTED_FILES") * harness_const(HARNESS_SPC700, "CASES_PER_FILE")
    for c in counts.values():
        c["not_run"] = max(full - c["states_total"], 0)
    if "Sampling first" in log:
        return "skipped", counts, "sampled run (not the full dataset): not a gate"
    return ("pass" if ok else "fail"), counts, None if ok else "gate failed"


def test_roms(log: str) -> tuple[str, dict, str | None]:
    verdict = cargo_verdict(log)
    counts = cargo_counts(log)
    skipped_rom = len(re.findall(r"\bSKIP", log))
    counts["rom_skips_reported"] = skipped_rom
    if verdict is None:
        return "fail", counts, "no `test result:` line in the log"
    return ("pass" if verdict == "ok" and counts["failed"] == 0 else "fail"), counts, None


def doc_drift(log: str) -> tuple[str, dict, str | None]:
    m = re.search(r"^check-doc-drift: (OK|(\d+) finding)", log, re.M)
    if not m:
        return "fail", {}, "no `check-doc-drift:` verdict line in the log"
    skipped = "cli/mcp/index skipped" in log
    counts = {"findings": 0 if m.group(1) == "OK" else int(m.group(2)), "checks_skipped_no_binary": skipped}
    return ("pass" if m.group(1) == "OK" else "fail"), counts, None


PARSERS = {
    "tom-harte-65816": tom_harte_65816,
    "tom-harte-spc700": tom_harte_spc700,
    "snes-test-roms": test_roms,
    "doc-drift": doc_drift,
}


def build_gate(name: str, log_path: str | None, outcome: str | None, run_url: str) -> dict:
    gate = {
        "name": name,
        "workflow": GATE_WHERE[name],
        "result": "skipped",
        "counts": {},
        "run_url": run_url,
    }
    from_outcome = outcome_result(outcome)
    if log_path is None or not Path(log_path).is_file():
        # no log: a CI outcome alone is a verdict without counts; nothing is nothing.
        if from_outcome in ("fail", "skipped"):
            gate["result"] = from_outcome
        elif from_outcome == "pass":
            gate["result"] = "fail"
            gate["note"] = "outcome success but no log to confirm it"
        return gate
    log = Path(log_path).read_text(errors="replace")
    result, counts, note = PARSERS[name](log)
    if from_outcome == "fail":
        result = "fail"
    elif from_outcome == "skipped" and result == "pass":
        result = "fail"
        note = "outcome skipped contradicts a passing log"
    gate["result"], gate["counts"] = result, counts
    if note:
        gate["note"] = note
    return gate


# ------------------------------------------------------------------ main

def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def workspace_version() -> str:
    m = re.search(r"^\[workspace\.package\][^\[]*?^version\s*=\s*\"([^\"]+)\"", (ROOT / "Cargo.toml").read_text(), re.M | re.S)
    return m.group(1) if m else "unknown"


def build(args: argparse.Namespace) -> dict:
    outcomes = {}
    for o in args.outcome:
        k, _, v = o.partition("=")
        if k not in GATE_NAMES or not v:
            sys.exit(f"oracle-json: bad --outcome {o!r} (NAME in {GATE_NAMES})")
        outcomes[k] = v
    env = os.environ
    if env.get("GITHUB_RUN_ID") and env.get("GITHUB_REPOSITORY"):
        run_url = f"{env.get('GITHUB_SERVER_URL', 'https://github.com')}/{env['GITHUB_REPOSITORY']}/actions/runs/{env['GITHUB_RUN_ID']}"
    else:
        run_url = "local"
    logs = {
        "tom-harte-65816": args.tom_harte_65816,
        "tom-harte-spc700": args.tom_harte_spc700,
        "snes-test-roms": args.snes_test_roms,
        "doc-drift": args.doc_drift,
    }
    commit = args.commit or env.get("GITHUB_SHA") or git("rev-parse", "HEAD")
    gates = [build_gate(n, logs[n], outcomes.get(n), run_url) for n in GATE_NAMES]
    try:
        core = git("log", "-1", "--format=%H", commit, "--", *CORE_PATHS)
    except subprocess.CalledProcessError:
        core = None
    now = args.now or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return {
        "schema": SCHEMA,
        "generated_at": now,
        "commit": commit,
        "luna_version": workspace_version(),
        "core_code_commit": core or None,
        "core_code_paths": CORE_PATHS,
        "gates": gates,
        "not_proven": NOT_PROVEN,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    for n in GATE_NAMES:
        ap.add_argument(f"--{n}", metavar="LOG", help=f"log of the {n} gate")
    ap.add_argument("--outcome", action="append", default=[], metavar="NAME=OUTCOME")
    ap.add_argument("--commit", help="full sha (default: $GITHUB_SHA, else HEAD)")
    ap.add_argument("--now", help="override generated_at (tests)")
    ap.add_argument("-o", "--out", default="ORACLE.json")
    args = ap.parse_args()
    doc = build(args)
    text = json.dumps(doc, indent=2) + "\n"
    if args.out == "-":
        sys.stdout.write(text)
    else:
        Path(args.out).write_text(text)
        print(f"oracle-json: wrote {args.out} ({', '.join(g['name'] + '=' + g['result'] for g in doc['gates'])})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
